#pragma once

#include "CoreMinimal.h"
#include "TomeTypes.h"

/** One character cell on the Tome, before it becomes 8x16 voxels. */
struct VOIDLITTOME_API FTomeCell
{
	TCHAR Char = TEXT(' ');
	FColor Color = FColor(201, 209, 224);
	float Glow = 0.f;
	ETomeEffect Effect = ETomeEffect::Rise;
	/** Raised height in rise units (1 = fully proud of the surface). */
	float Height = 1.f;
	/** Reading-order index of this character in the log (-1 for chrome such as the status bar). Drives the
	 *  typewriter stagger: newly arrived text rises one character after another. */
	int32 Serial = -1;
};

using FTomeLine = TArray<FTomeCell>;

/** 8x16 voxel bitmap glyphs (DejaVu Sans Mono Bold, generated by Tools/gen_tome_glyphs.py). */
class VOIDLITTOME_API FTomeGlyphFont
{
public:
	static constexpr int32 Width = 8;
	static constexpr int32 Height = 16;

	/** 16 rows, MSB = leftmost voxel. Unknown characters fall back to '?'. */
	static const uint8* GetRows(uint32 Codepoint);
};

/**
 * Lays frames out as a scrolling log of character lines, then composes the visible page:
 *   row 0      status bar (hull, stress, lumen, chapter)
 *   row 1      rule
 *   ...        the tail of the log
 *   Rows-2     the current prompt (the obstacles present, "What do you do?")
 *   Rows-1     the player's input line, with a cursor
 */
class VOIDLITTOME_API FTomeTypesetter
{
public:
	explicit FTomeTypesetter(int32 InColumns = 38, int32 InMaxLines = 600);

	/** Changing the width clears the log (no reflow). */
	void SetColumns(int32 InColumns);
	int32 GetColumns() const { return Columns; }

	/** Appends a frame to the log and returns the serial of its first character. */
	int32 AppendFrame(const FTomeFrame& Frame);
	void Clear();

	void ComposePage(int32 Rows, const FTomeStatus& Status, const FString& Input, bool bCursorOn,
		TArray<FTomeLine>& OutPage) const;

	int32 NumLines() const { return Lines.Num(); }

private:
	void AppendBlock(const FTomeBlock& Block);
	void AppendWrapped(const TArray<FTomeSpan>& Spans, int32 FirstIndent, int32 RestIndent, bool bCenter, float Height);
	void AppendBlank();
	void Trim();
	FTomeCell MakeCell(TCHAR C, const FTomeSpan& Span, float Height);
	void WriteText(FTomeLine& Line, int32 Col, const FString& Text, FColor Color, float Glow,
		ETomeEffect Effect = ETomeEffect::None, float Height = 0.6f) const;

	int32 Columns;
	int32 MaxLines;
	int32 NextSerial = 0;
	TArray<FTomeLine> Lines;
	TArray<FTomeSpan> PromptSpans;
};
