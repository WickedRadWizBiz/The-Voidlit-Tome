"""Generate the Tome's voxel glyph table (8x16 cells) from DejaVu Sans Mono Bold.

    python gen_tome_glyphs.py [--font-dir /usr/share/fonts/truetype/dejavu] > ../Source/VoidlitTome/Private/TomeGlyphData.inl

Requires Pillow. Each glyph is 16 rows of one byte (MSB = leftmost voxel). DejaVu fonts are distributed under
the Bitstream Vera license (with DejaVu changes in the public domain); the notice is reproduced in the output.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

W, H, SIZE, DY, THRESHOLD = 8, 16, 13, -2, 110
EXTRA = "“”‘’—–…•·×▲◆●⟳█░→"

NOTICE = """// Generated by Tools/gen_tome_glyphs.py from DejaVu Sans Mono Bold (8x16 voxel cells). Do not edit.
//
// DejaVu fonts: Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream Vera is a trademark of
// Bitstream, Inc. DejaVu changes are in the public domain. Permission is hereby granted, free of charge, to any
// person obtaining a copy of the fonts accompanying this license ("Fonts") and associated documentation files
// (the "Font Software"), to reproduce and distribute the Font Software, including without limitation the rights
// to use, copy, merge, publish, distribute, and/or sell copies of the Font Software, subject to the conditions in
// the Bitstream Vera license (https://dejavu-fonts.github.io/License.html). These bitmaps are a derived work
// and are not named "Bitstream" or "Vera"."""


SUBSTITUTE = {"\u27f3": "\u21bb"}  # clockwise gapped circle arrow -> clockwise open circle arrow


def has_glyph(font: ImageFont.FreeTypeFont, ch: str) -> bool:
    """True unless the font would draw its .notdef box (compared against a private-use codepoint)."""
    return bytes(font.getmask(ch)) != bytes(font.getmask("\ue000")) and bool(font.getmask(ch).getbbox())


def rasterize(ch: str, fonts: list[ImageFont.FreeTypeFont]) -> list[int]:
    ch = SUBSTITUTE.get(ch, ch)
    for font in fonts:
        if ch == " " or has_glyph(font, ch):
            break
    else:
        raise SystemExit(f"no font has U+{ord(ch):04X}")
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, DY if font is fonts[0] else 0), ch, font=font, fill=255)
    rows = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if img.getpixel((x, y)) > THRESHOLD:
                bits |= 0x80 >> x
        rows.append(bits)
    return rows


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--font-dir", default="/usr/share/fonts/truetype/dejavu")
    args = p.parse_args()
    d = Path(args.font_dir)
    fonts = [ImageFont.truetype(str(d / "DejaVuSansMono-Bold.ttf"), SIZE),
             ImageFont.truetype(str(d / "DejaVuSans-Bold.ttf"), SIZE - 1),
             ImageFont.truetype(str(d / "DejaVuSans.ttf"), SIZE - 1)]
    chars = [chr(c) for c in range(32, 127)] + list(EXTRA)
    print(NOTICE)
    print(f"static constexpr int32 GTomeGlyphWidth = {W};")
    print(f"static constexpr int32 GTomeGlyphHeight = {H};")
    print("struct FTomeGlyphRow { uint32 Codepoint; uint8 Rows[16]; };")
    print("static const FTomeGlyphRow GTomeGlyphs[] = {")
    for ch in chars:
        rows = ", ".join(f"0x{b:02X}" for b in rasterize(ch, fonts))
        label = {"\\": "backslash", "'": "quote"}.get(ch, ch) if ch.isascii() else f"U+{ord(ch):04X}"
        print(f"\t{{ 0x{ord(ch):04X}, {{ {rows} }} }}, // {label}")
    print("};")


if __name__ == "__main__":
    main()
